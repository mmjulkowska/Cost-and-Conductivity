"""v5 GRANAR inputs for ALL usable sections of Emily Miller's measurements (Nov 2026).
One input file per section x measured cell (replicate k = 1..4), at the corrected scale (1.03214286e-7 mm2 per px).
Rule (decided by Magda Julkowska, 7 Nov 2026):
  stele layer_diameter  = 2*sqrt(A/pi), A = Emily's vasculature (stele) total area
  stele cell_diameter   = Emily's vasculature cell #k (segment median of measured vasculature cells if #k missing)
  endodermis/epidermis  = Emily's endodermis / epidermis cell #k
  cortex cell_diameter  = Emily's cortex cell #k ; cortex n_layers = Emily's layer count - 1 (+1 exodermis layer)
  pericycle 0.021 mm, exodermis 0.02 mm, xylem max 0.035 mm, phloem 0.01, hair 0.07, pith 0.03/0.01
  cell diameter = 2*sqrt(A/pi) of the measured cell area.
Excluded: DSC_00425PR (row 4, torn section) and DSC_0030RT (row 60, no stele visible); rows lacking vasculature
total, layer count, or the cortex/endodermis/epidermis cell #k.
Run from anywhere: python 1_granar/make_granar_inputs.py. Reads the sheet from paths.SHEET; writes 1_granar/granar_params/ and 1_granar/v5_replicates.csv."""
import os, sys; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from paths import *
import pandas as pd, numpy as np, os
F=1.03214286e-7; PDIR=GRANAR_PARAMS; os.makedirs(PDIR,exist_ok=True)
X=pd.read_excel(SHEET); X.insert(0,'MPn',range(1,len(X)+1))
seg=lambda n:'MP' if n<=9 else 'MM' if n<=20 else 'MT' if n<=26 else 'LP' if n<=40 else 'LM' if n<=50 else 'LT'
X['seg']=X.MPn.map(seg); num=lambda c: pd.to_numeric(X[c],errors='coerce')
P=lambda t,k: [c for c in X.columns if c.strip().startswith(t) and f'#{k}' in c and 'pixels' in c][0]
d=lambda px: 2*np.sqrt(px*F/np.pi)            # mm
EXCL={4:'torn section (DSC_00425PR)',60:'no stele visible (DSC_0030RT)'}
vasc=pd.DataFrame({k:num(P('Vasculature Cell Size Individual',k)) for k in (1,2,3,4)})
seg_vasc_med={s:float(np.nanmedian(d(vasc[X.seg==s].values.ravel()[vasc[X.seg==s].values.ravel()>0]))) for s in X.seg.unique()}
TEMPLATE='''<granar>
<!-- v5 input for {id} (Nov 2026): Emily Miller's row {n} ({img}, {seg}), measured cell #{k}; sizes = 2*sqrt(area/pi) at 1.03214286e-7 mm2/px. Generated by 1_granar/make_granar_inputs.py -->
<planttype param="2"/>
<randomness param="2"/>
<secondarygrowth param="0"/>
<stele cell_diameter="{stele_cell:.6g}" n_layers="1" layer_diameter="{stele_layer:.6g}" order="1"/>
<pericycle cell_diameter="0.021" n_layers="1" order="2"/>
<endodermis cell_diameter="{endo:.6g}" n_layers="1" order="3"/>
<cortex cell_diameter="{cortex:.6g}" n_layers="{ncx}" order="5"/>
<exodermis cell_diameter="0.02" n_layers="1" order="7"/>
<epidermis cell_diameter="{epi:.6g}" n_layers="1" order="8"/>
<xylem max_size="0.035" n_files="1" order="1.5" ratio="3.3"/>
<phloem max_size="0.01" n_files="1" n_layers="0"/>
<aerenchyma proportion="0.0" n_files="0" type="1"/>
<hair length="0.07" n_files="3"/>
<pith layer_diameter="0.03" cell_diameter="0.01"/>
</granar>
'''
rows=[]
for i,r in X.iterrows():
    n=int(r.MPn); vt=num('Vasculature Total (pixels)')[i]; nl=num('Number of Cortex Layers')[i]
    for k in (1,2,3,4):
        c,en,ep=[num(P(t,k))[i] for t in ('Cortex Cell individual','Endodermis Cell Individual','Epidermis Cell Individual')]
        why=EXCL.get(n) or ('no vasculature total' if not vt>0 else 'no layer count' if pd.isna(nl) else
             None if all(pd.notna(v) and v>0 for v in (c,en,ep)) else 'cell #%d not measured'%k)
        rec=dict(id=f'MP{n}_cell{k}',MPn=n,image=str(r['Image Name']).strip(),segment=r.seg,k=k,used=why is None,reason=why or '')
        if why is None:
            vk=vasc.loc[i,k]; sc=d(vk) if vk>0 else seg_vasc_med[r.seg]
            p=dict(id=rec['id'],n=n,img=rec['image'],seg=r.seg,k=k,stele_cell=sc,stele_layer=d(vt),endo=d(en),cortex=d(c),epi=d(ep),ncx=int(nl)-1)
            open(os.path.join(PDIR,rec['id']+'.xml'),'w').write(TEMPLATE.format(**p))
            rec.update(stele_cell_mm=sc,stele_cell_from='measured' if vk>0 else 'segment median',stele_layer_mm=d(vt),cortex_mm=d(c),endo_mm=d(en),epi_mm=d(ep),emily_layers=int(nl))
        rows.append(rec)
R=pd.DataFrame(rows); R.to_csv(REPLICATES,index=False)
print(R.used.sum(),'input files;',R[R.used].MPn.nunique(),'sections;',(R[R.used].stele_cell_from=='segment median').sum(),'with segment-median stele cell')
